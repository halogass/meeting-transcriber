"""Meetings on disk: one folder per meeting under data/meetings/<id>/.

  meta.json        title, times, status, speaker names
  mic.raw|wav      your microphone (raw while recording, WAV after)
  call.raw|wav     call / system audio
  upload.wav       uploaded recording (upload mode)
  live.jsonl       live captions as they were produced
  transcript.json  final speaker-attributed transcript
  summary.md       AI summary
  audio.opus       mixed audio for playback
"""

from __future__ import annotations

import json
import secrets
import shutil
import threading
from datetime import datetime
from pathlib import Path

from .config import MEETINGS_DIR

_lock = threading.Lock()


def new_id() -> str:
    return datetime.now().strftime("%Y%m%d-%H%M%S-") + secrets.token_hex(2)


def meeting_dir(mid: str) -> Path:
    # ids are generated by us; reject anything that could escape the folder
    if not mid or "/" in mid or ".." in mid or "\\" in mid:
        raise ValueError("bad meeting id")
    return MEETINGS_DIR / mid


def create(title: str, mode: str, user_name: str) -> dict:
    mid = new_id()
    d = meeting_dir(mid)
    d.mkdir(parents=True, exist_ok=False)
    now = datetime.now().astimezone().isoformat(timespec="seconds")
    meta = {
        "id": mid,
        "title": title.strip() or f"Meeting {datetime.now():%d %b %Y %H:%M}",
        "created_at": now,
        "ended_at": None,
        "duration": 0.0,
        "mode": mode,  # "live" | "upload"
        "status": "recording" if mode == "live" else "queued",
        "progress": 0.0,
        "stage": "",
        "error": None,
        "user_name": user_name,
        "speakers": {},  # label -> display name
        "language": "",
    }
    write_meta(mid, meta)
    return meta


def read_meta(mid: str) -> dict:
    return json.loads((meeting_dir(mid) / "meta.json").read_text())


def write_meta(mid: str, meta: dict) -> None:
    p = meeting_dir(mid) / "meta.json"
    with _lock:
        tmp = p.with_suffix(".tmp")
        tmp.write_text(json.dumps(meta, indent=2, ensure_ascii=False))
        tmp.replace(p)


def update_meta(mid: str, **changes) -> dict:
    with _lock:
        p = meeting_dir(mid) / "meta.json"
        meta = json.loads(p.read_text())
        meta.update(changes)
        tmp = p.with_suffix(".tmp")
        tmp.write_text(json.dumps(meta, indent=2, ensure_ascii=False))
        tmp.replace(p)
    return meta


def list_meetings(query: str = "") -> list[dict]:
    if not MEETINGS_DIR.exists():
        return []
    q = query.strip().lower()
    out = []
    for d in sorted(MEETINGS_DIR.iterdir(), reverse=True):
        mp = d / "meta.json"
        if not mp.exists():
            continue
        try:
            meta = json.loads(mp.read_text())
        except json.JSONDecodeError:
            continue
        if q:
            hay = meta.get("title", "").lower()
            tp = d / "transcript.json"
            if q not in hay and tp.exists():
                hay += " " + " ".join(s["text"] for s in json.loads(tp.read_text()).get("segments", [])).lower()
            if q not in hay:
                continue
        out.append(meta)
    return out


def append_live(mid: str, item: dict) -> None:
    with open(meeting_dir(mid) / "live.jsonl", "a", encoding="utf-8") as f:
        f.write(json.dumps(item, ensure_ascii=False) + "\n")


def read_live(mid: str) -> list[dict]:
    p = meeting_dir(mid) / "live.jsonl"
    if not p.exists():
        return []
    return [json.loads(line) for line in p.read_text(encoding="utf-8").splitlines() if line.strip()]


def write_transcript(mid: str, transcript: dict) -> None:
    (meeting_dir(mid) / "transcript.json").write_text(json.dumps(transcript, indent=1, ensure_ascii=False))


def read_transcript(mid: str) -> dict | None:
    p = meeting_dir(mid) / "transcript.json"
    return json.loads(p.read_text()) if p.exists() else None


def read_summary(mid: str) -> str | None:
    p = meeting_dir(mid) / "summary.md"
    return p.read_text(encoding="utf-8") if p.exists() else None


def write_summary(mid: str, text: str) -> None:
    (meeting_dir(mid) / "summary.md").write_text(text, encoding="utf-8")


def delete(mid: str) -> None:
    shutil.rmtree(meeting_dir(mid))
